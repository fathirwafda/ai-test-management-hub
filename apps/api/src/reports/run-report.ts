import { RESULT_STATUSES, TRIAGE_LABELS, formatPercent, type RunDetail, type RunItem } from "@hub/shared";

const duration = (ms: number | null) => (ms === null ? "" : ms < 1000 ? `${ms} ms` : `${(ms / 1000).toFixed(1)} s`);
const firstLine = (s: string) => s.split("\n")[0] ?? "";

// ---------- CSV ----------

/** RFC 4180 quoting, plus a leading quote for cells a spreadsheet would treat as a formula. */
export function csvCell(value: string | number | null | undefined): string {
  let s = value === null || value === undefined ? "" : String(value);
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function runToCsv(run: RunDetail): string {
  const header = [
    "key",
    "title",
    "platform",
    "type",
    "priority",
    "status",
    "duration_ms",
    "executed_by",
    "executed_at",
    "comment",
    "failure_message",
    "triage_category",
    "evidence_files",
    "automation_ref",
  ];
  const rows = run.items.map((i) => [
    i.caseKey,
    i.caseTitle,
    i.platform,
    i.type,
    i.priority,
    i.status,
    i.durationMs ?? "",
    i.executedBy,
    i.executedAt ?? "",
    i.comment,
    i.failureMessage,
    i.triage?.category ?? "",
    i.attachments.map((a) => a.fileName).join(" | "),
    i.automationRef ?? "",
  ]);
  return [header, ...rows].map((r) => r.map(csvCell).join(",")).join("\r\n") + "\r\n";
}

// ---------- Markdown ----------

const mdEscape = (s: string) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

function summaryLines(run: RunDetail): string[] {
  const c = run.counts;
  return [
    `- **Environment:** ${run.environment || "–"}  `,
    `- **Build:** ${run.build || "–"}  `,
    `- **Status:** ${run.status}${run.closedAt ? ` (closed ${run.closedAt})` : ""}  `,
    `- **Created:** ${run.createdAt}  `,
    `- **Progress:** ${formatPercent(run.progress)} executed (${c.total - c.untested}/${c.total})  `,
    `- **Pass rate:** ${formatPercent(run.passRate, 1)} (passed / (passed + failed + blocked + retest))`,
  ];
}

const needsAttention = (run: RunDetail) =>
  run.items.filter((i) => i.status === "failed" || i.status === "blocked" || i.status === "retest");

export function runToMarkdown(run: RunDetail, generatedAt = new Date().toISOString()): string {
  const out: string[] = [`# Test run report: ${run.name}`, "", ...summaryLines(run), ""];
  out.push("## Results", "", "| Status | Count |", "| --- | ---: |");
  for (const s of RESULT_STATUSES) out.push(`| ${s} | ${run.counts[s]} |`);
  out.push("");

  const attention = needsAttention(run);
  if (attention.length) {
    out.push("## Needs attention", "");
    for (const i of attention) {
      out.push(`### ${i.caseKey} ${mdEscape(i.caseTitle)} (${i.status})`, "");
      if (i.failureMessage) out.push("```text", firstLine(i.failureMessage).slice(0, 500), "```", "");
      if (i.comment) out.push(`Comment: ${mdEscape(i.comment)}`, "");
      if (i.triage) {
        out.push(
          `Triage (AI-suggested, accepted by a person): **${TRIAGE_LABELS[i.triage.category]}**. ${mdEscape(i.triage.summary)}`,
          "",
        );
      }
    }
  }

  out.push(
    "## All cases",
    "",
    "| Key | Title | Platform | Type | Status | Duration | Executed by | Evidence |",
    "| --- | --- | --- | --- | --- | ---: | --- | ---: |",
  );
  for (const i of run.items) {
    out.push(
      `| ${i.caseKey} | ${mdEscape(i.caseTitle)} | ${i.platform} | ${i.type} | ${i.status} | ${duration(i.durationMs)} | ${mdEscape(i.executedBy)} | ${i.attachments.length} |`,
    );
  }
  if (run.notes) out.push("", "## Notes", "", run.notes);
  out.push("", `_Generated by AI Test Management Hub at ${generatedAt}._`, "");
  return out.join("\n");
}

// ---------- HTML ----------

export function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);
}

const STATUS_COLOURS: Record<RunItem["status"], string> = {
  passed: "#1a7f37",
  failed: "#cf222e",
  blocked: "#9a6700",
  retest: "#8250df",
  skipped: "#57606a",
  untested: "#8c959f",
};

export function runToHtml(run: RunDetail, generatedAt = new Date().toISOString()): string {
  const e = escapeHtml;
  const c = run.counts;
  const bar = RESULT_STATUSES.filter((s) => c[s] > 0)
    .map((s) => `<span style="flex:${c[s]};background:${STATUS_COLOURS[s]}" title="${s}: ${c[s]}"></span>`)
    .join("");
  const rows = run.items
    .map(
      (i) => `<tr>
  <td>${e(i.caseKey)}</td><td>${e(i.caseTitle)}${i.failureMessage ? `<div class="err">${e(firstLine(i.failureMessage).slice(0, 300))}</div>` : ""}</td>
  <td>${e(i.platform)}</td><td>${e(i.type)}</td>
  <td><span class="pill" style="background:${STATUS_COLOURS[i.status]}">${e(i.status)}</span></td>
  <td class="num">${e(duration(i.durationMs))}</td><td>${e(i.executedBy)}</td><td class="num">${i.attachments.length}</td>
</tr>`,
    )
    .join("\n");
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Test run report: ${e(run.name)}</title>
<style>
  body { font: 14px/1.5 system-ui, sans-serif; color: #1f2328; margin: 2rem auto; max-width: 1100px; padding: 0 1rem; }
  h1 { font-size: 1.5rem; } dl { display: grid; grid-template-columns: max-content 1fr; gap: .25rem 1rem; }
  dt { color: #57606a; } .bar { display: flex; height: 12px; border-radius: 6px; overflow: hidden; background: #eaeef2; margin: 1rem 0; }
  table { border-collapse: collapse; width: 100%; } th, td { text-align: left; padding: .4rem .5rem; border-bottom: 1px solid #d0d7de; vertical-align: top; }
  th { background: #f6f8fa; } .num { text-align: right; } .pill { color: #fff; border-radius: 999px; padding: 0 .5rem; font-size: 12px; }
  .err { color: #cf222e; font-family: ui-monospace, monospace; font-size: 12px; margin-top: .2rem; }
  footer { color: #57606a; margin-top: 2rem; font-size: 12px; }
</style>
</head>
<body>
<h1>Test run report: ${e(run.name)}</h1>
<dl>
  <dt>Environment</dt><dd>${e(run.environment || "–")}</dd>
  <dt>Build</dt><dd>${e(run.build || "–")}</dd>
  <dt>Status</dt><dd>${e(run.status)}</dd>
  <dt>Progress</dt><dd>${formatPercent(run.progress)} executed (${c.total - c.untested}/${c.total})</dd>
  <dt>Pass rate</dt><dd>${formatPercent(run.passRate, 1)}</dd>
  <dt>Results</dt><dd>${RESULT_STATUSES.map((s) => `${s}: ${c[s]}`).join(" · ")}</dd>
</dl>
<div class="bar" role="img" aria-label="Result distribution">${bar}</div>
<table>
<thead><tr><th>Key</th><th>Title</th><th>Platform</th><th>Type</th><th>Status</th><th class="num">Duration</th><th>Executed by</th><th class="num">Evidence</th></tr></thead>
<tbody>
${rows}
</tbody>
</table>
${run.notes ? `<h2>Notes</h2><p>${e(run.notes).replace(/\n/g, "<br>")}</p>` : ""}
<footer>Generated by AI Test Management Hub at ${e(generatedAt)}.</footer>
</body>
</html>
`;
}
